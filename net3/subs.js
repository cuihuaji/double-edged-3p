(function () {
  function norm(s) {
    return String(s || "")
      .replace(/<br\s*\/?>/gi, " ")
      .replace(/\^/g, " ")
      .replace(/&quot;/g, "\"")
      .replace(/&amp;/g, "&")
      .toUpperCase()
      .replace(/[^A-Z0-9]+/g, " ")
      .trim();
  }
  var map = {};
  for (var i = 0; i < window.DE_SUBS.length; i++) {
    map[norm(window.DE_SUBS[i][0])] = window.DE_SUBS[i][1];
  }
  window.DE_LOOKUP = function (raw) { return map[norm(raw)] || ""; };
  window.DE_NORM = norm;
})();

/* ---- 运行时采集：把 AVM 里所有可见文本框的内容读出来 ----
 * 实测：游戏里能读到的文字都在 TextField 的 $Bg_text 上（舞台树 → 属性）。
 * 遍历深度 9 足够覆盖 441 个节点，每 300ms 跑一次开销可忽略。 */
/* 从一个 TextField 包装对象里取字符串。
 * 实测两种存法：
 *   1) 代码创建的文本框 → 包装对象上的 $Bg_text
 *   2) 元件里嵌的文本框（对话气泡就是这种）→ 包装对象._adaptee._text
 * 只读 _text 不够，_iText 在部分状态下才是最新的。 */
function deFieldText(o) {
  try {
    var a = o._adaptee || o;
    if (typeof a._text === "string" && a._text) return a._text;
    if (typeof a._iText === "string" && a._iText) return a._iText;
    if (typeof a.text === "string" && a.text) return a.text;
  } catch (e) {}
  return "";
}

/* 设计期占位文字，气泡没说话时留着它，不能当字幕 */
function dePlaceholder(s) {
  return /^(\s*speech text\s*)+$/i.test(s);
}

/* ---- 运行时采集 ----
 * 沿舞台树下降时累计「有效透明度」和可见性：气泡隐藏时 alpha 归零，
 * 文本却还留着上一句，只看文本会一直显示过期字幕。
 * 实测 441 个节点，一次遍历约 0.3ms，300ms 轮询没有压力。 */
/* 采集器：轻量优先。
 * 实测这就是打怪卡顿的来源之一 —— 每 300ms 全树遍历 + getOwnPropertyNames
 * （440+ 节点，怪一多还要涨）。改成「注册表」：全树只做一次，
 * 把带 $BgspeechText 的气泡节点登记下来，之后每帧只读那两三个对象。 */
window.DE_collect = (function () {
  var reg = [];            /* 学到的气泡节点 */
  var hudTexts = [];       /* HUD / 界面文字缓存 */
  var scanAt = 0;          /* 上次全树扫描 */
  var SCAN_MS = 1500;      /* 全树扫描间隔（发现新气泡、刷新 HUD） */

  function clampA(v) {
    if (typeof v !== "number" || !isFinite(v)) return 1;
    if (v <= 0) return 0;
    if (v >= 1) return 1;
    return v;
  }
  function deHas(o, name) {
    try { return o[name] !== undefined && o[name] !== null; } catch (e) { return false; }
  }
  /* 自身到祖先的有效透明度：气泡整体在淡入淡出 */
  function effAlpha(n, maxUp) {
    var a = 1, o = n, k = 0;
    while (o && k < maxUp) {
      var al = 1; try { if (typeof o.alpha === "number") al = clampA(o.alpha); } catch (e) {}
      if (al <= 0) return 0;
      if (al < 1) a *= al;
      var vis = true; try { if (o.visible === false) vis = false; } catch (e) {}
      if (!vis) return 0;
      try { o = o.parent; } catch (e) { o = null; }
      k++;
    }
    return a;
  }

  function scan(w, st) {
    var roots = [], sc;
    for (var si = 0; si < 16; si++) {
      sc = null; try { sc = st.getChildAt(si); } catch (e) { sc = null; }
      if (!sc) break;
      roots.push(sc);
    }
    if (!roots.length) roots.push(st);
    var seen = new Set(), found = [], hud = [];
    function walk(o, d, ea, vis) {
      if (!o || d > 10 || seen.has(o)) return;
      seen.add(o);
      var v = vis, al = 1;
      try { if (o.visible === false) v = false; } catch (e) {}
      try { if (typeof o.alpha === "number") al = clampA(o.alpha); } catch (e) {}
      var eff = ea * al;
      if (deHas(o, "$BgspeechText")) {
        found.push(o);
        var f = null; try { f = o.$BgspeechText; } catch (e) {}
        var t3 = f ? deFieldText(f) : "";
        if (t3 && t3.trim() && v && eff > 0.35 && !dePlaceholder(t3)) hud.push(t3.trim());
      } else if (deHas(o, "$Bg_text")) {
        var t1 = ""; try { t1 = o.$Bg_text; } catch (e) {}
        if (typeof t1 === "string" && t1.trim() && v && eff > 0.05) hud.push(t1.trim());
      }
      var n = 0; try { n = o.numChildren || 0; } catch (e) {}
      for (var i = 0; i < n; i++) {
        var c = null; try { c = o.getChildAt(i); } catch (e) {}
        if (c) walk(c, d + 1, eff, v);
      }
    }
    for (var ri = 0; ri < roots.length; ri++) walk(roots[ri], 0, 1, true);
    reg = found;
    var uniq = [];
    for (var k = 0; k < hud.length; k++) if (uniq.indexOf(hud[k]) < 0) uniq.push(hud[k]);
    hudTexts = uniq;
    scanAt = Date.now();
  }

  return function (w) {
    try {
      var pg = w.AVMPlayerPoki && w.AVMPlayerPoki._avmHandler && w.AVMPlayerPoki._avmHandler._playerglobal;
      var st = pg && pg._stage && pg._stage._stage;
      if (!st) return [];
      var now = Date.now();
      var out = [];

      /* 1) 已登记的气泡：O(气泡数)，通常 1~3 个对象 */
      for (var i = reg.length - 1; i >= 0; i--) {
        var n = reg[i], alive = true;
        try { alive = !!n.parent; } catch (e) { alive = false; }
        if (!alive) { reg.splice(i, 1); continue; }
        var f = null; try { f = n.$BgspeechText; } catch (e) {}
        var tx = f ? deFieldText(f) : "";
        if (!tx || !tx.trim() || dePlaceholder(tx)) continue;
        if (effAlpha(n, 10) > 0.35) out.push(tx.trim());
      }

      /* 2) 首次、找不到气泡、或超过间隔 → 全树扫一次 */
      if (!reg.length || now - scanAt > SCAN_MS) scan(w, st);

      /* 3) HUD 文本来自最近一次扫描的缓存 */
      for (var j = 0; j < hudTexts.length; j++) {
        if (out.indexOf(hudTexts[j]) < 0) out.push(hudTexts[j]);
      }
      out.sort(function (x, y) { return y.length - x.length; });
      return out;
    } catch (e) { return []; }
  };
})();/* ---- 匹配：支持打字机（气泡逐字出现）----
 * 屏幕上只有半句时，用「屏幕文本是词条前缀」来认定是同一条台词。 */
window.DE_MATCH = function (raw) {
  try {
    var n = window.DE_NORM(raw);
    if (!n || n.length < 3) return "";
    var exact = window.DE_LOOKUP(raw);
    if (exact) return exact;
    var best = "", bestLen = 0, revBest = "", revLen = 0;
    for (var i = 0; i < window.DE_SUBS.length; i++) {
      var k = window.DE_NORM(window.DE_SUBS[i][0]);
      if (!k) continue;
      /* 正向（打字机）：屏幕上只是词条的前半句 */
      if (n.length >= 4 && k.indexOf(n) === 0) {
        if (n.length > bestLen) { best = window.DE_SUBS[i][1]; bestLen = n.length; }
      } else if (n.length >= 5 && n.indexOf(k) === 0 && k.length * 10 >= n.length * 7) {
        /* 反向：气泡多带了尾巴或标点（HISSS 与 HISSSS 这类），
         * 取最长的那个词条做近似，避免短词误伤 */
        if (k.length > revLen) { revBest = window.DE_SUBS[i][1]; revLen = k.length; }
      }
    }
    return best || revBest;
  } catch (e) { return ""; }
};

/* ---- 字幕条（房主、好友共用）---- */
window.DE_bar = (function () {
  var el = null, inner = null, hideTimer = 0, enabled = true;
  function ensure() {
    if (el && el.parentNode) return;
    el = document.createElement("div");
    el.id = "de-sub";
    el.style.cssText = "position:fixed;left:0;right:0;bottom:16px;z-index:9999;display:none;" +
      "pointer-events:none;text-align:center;" +
      "font:600 16px/1.45 -apple-system,'Segoe UI','Microsoft YaHei',sans-serif;" +
      "color:#fff;text-shadow:0 2px 10px rgba(0,0,0,.95),0 0 3px rgba(0,0,0,.85)";
    inner = document.createElement("span");
    inner.style.cssText = "display:inline-block;max-width:min(92vw,860px);padding:5px 14px;" +
      "border-radius:10px;background:rgba(0,0,0,.62)";
    el.appendChild(inner);
    document.body.appendChild(el);
  }
  function set(text, holdMs) {
    ensure();
    if (!enabled || !text) { el.style.display = "none"; return; }
    inner.textContent = text;
    el.style.display = "block";
    clearTimeout(hideTimer);
    hideTimer = setTimeout(function () { el.style.display = "none"; }, holdMs || 7000);
  }
  set.toggle = function () {
    enabled = !enabled;
    if (!enabled) { try { el.style.display = "none"; } catch (e) {} }
    window.__diag && window.__diag.report("sub", enabled ? "字幕已开" : "字幕已关", "", "info");
    return enabled;
  };
  set.enabled = function () { return enabled; };
  return set;
})();

